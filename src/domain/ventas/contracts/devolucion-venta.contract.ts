import { positiveDecimalQuantity, DecimalQuantityError } from "../../shared/value-objects/DecimalQuantity";

const returnQuantity = (value: unknown): bigint => {
  try { return positiveDecimalQuantity(value); }
  catch (error) {
    if (error instanceof DecimalQuantityError) throw new Error("CREDIT_NOTE_QUANTITY_INVALID");
    throw error;
  }
};

/** Commercial return authority. Fiscal documents and money/stock ledgers remain separate. */
export const CREDIT_NOTE_COMMERCIAL_TYPE = "devolucion_venta" as const;
export type CreditNoteReturnCondition = "SELLABLE" | "DAMAGED";
export type CreditNoteRefundMethod = "EFECTIVO" | "DIGITAL" | "TARJETA";
export type CreditNoteReturnReceipt = Readonly<{
  originalLineId: string;
  quantity: string;
  warehouseId?: string;
  condition: CreditNoteReturnCondition;
  /** Damaged goods are physically discarded; the original sale already deducted stock. */
  disposition?: "DISCARDED";
}>;
export type CreditNoteRefundConfirmation = Readonly<{
  amountCents: number;
  method: CreditNoteRefundMethod;
  cashBoxId: string;
  cashShiftId: string;
  confirmedAt: number;
  evidenceReference?: string;
}>;
/** A client request has a stable opaque identity before its first network attempt. */
export type CreditNoteCommercialRequest = Readonly<{
  requestId: string;
  receipts: readonly CreditNoteReturnReceipt[];
  refund: CreditNoteRefundConfirmation | null;
}>;
export type CreditNoteCommercialMoneyFacts = Readonly<{
  clientId?: string;
  accountId?: string;
  saleDebtMovementId?: string;
  outstandingDebtCents: number;
  refundablePaidCents: number;
  appliedCustomerBalanceCents: number;
  unverifiedCents: number;
}>;
export type CreditNoteCommercialEffect = "PENDING" | "DONE";
export type CreditNoteCommercialBatch = Readonly<{
  request: CreditNoteCommercialRequest;
  requestFingerprint: string;
  actorId: string;
  createdAt: number;
  /** Reserved once by the shared authority, never regenerated by a retry/device. */
  refundMovementId?: string;
  stockIdentities: readonly Readonly<{
    movementId: string; movementLineId: string; movementOperationId: string; idempotencyKey: string;
  }>[];
  stock: CreditNoteCommercialEffect;
  refund: CreditNoteCommercialEffect;
}>;
export type CreditNoteCommercialOperation = Readonly<{
  type: typeof CREDIT_NOTE_COMMERCIAL_TYPE;
  schemaVersion: 1;
  commercialOperationId: string;
  fiscalOperationId: string;
  tenantId: string;
  originalDocumentId: string;
  creditNoteDocumentId: string;
  saleId: string;
  saleSnapshotId: string;
  currency: "PEN" | "USD";
  createdBy: string;
  createdAt: number;
  updatedAt: number;
  adjustmentCents: number;
  returnLines: readonly Readonly<{ originalLineId: string; quantity: string; stockExpected: boolean }>[];
  moneyFacts: CreditNoteCommercialMoneyFacts;
  debtReductionCents: number;
  customerBalanceRestoreCents: number;
  debtIdempotencyKey: string;
  debt: CreditNoteCommercialEffect;
  batches: readonly CreditNoteCommercialBatch[];
  status: "PENDING" | "APPLYING" | "COMPLETED" | "ACTION_REQUIRED";
  lastError?: string;
}>;
const opaque = (value: unknown): value is string => typeof value === "string" && value.trim().length > 0;
const cents = (value: unknown): value is number => Number.isSafeInteger(value) && Number(value) >= 0;

export function assertCreditNoteCommercialRequest(raw: unknown): asserts raw is CreditNoteCommercialRequest {
  const value = raw as CreditNoteCommercialRequest;
  if (!value || !opaque(value.requestId) || !Array.isArray(value.receipts) || value.receipts.length > 256)
    throw new Error("CREDIT_NOTE_RETURN_REQUEST_INVALID");
  for (const receipt of value.receipts) {
    if (!receipt || !opaque(receipt.originalLineId) || !["SELLABLE", "DAMAGED"].includes(receipt.condition))
      throw new Error("CREDIT_NOTE_RETURN_RECEIPT_INVALID");
    returnQuantity(receipt.quantity);
    if (receipt.condition === "SELLABLE" && (!opaque(receipt.warehouseId) || receipt.disposition !== undefined))
      throw new Error("CREDIT_NOTE_RETURN_WAREHOUSE_REQUIRED");
    if (receipt.condition === "DAMAGED" && receipt.disposition !== "DISCARDED")
      throw new Error("CREDIT_NOTE_RETURN_DISPOSITION_REQUIRED");
  }
  if (value.refund === null) return;
  const refund = value.refund;
  if (!refund || !cents(refund.amountCents) || !refund.amountCents ||
      !["EFECTIVO", "DIGITAL", "TARJETA"].includes(refund.method) ||
      !opaque(refund.cashBoxId) || !opaque(refund.cashShiftId) ||
      !Number.isSafeInteger(refund.confirmedAt) || refund.confirmedAt <= 0 ||
      (refund.method !== "EFECTIVO" && !opaque(refund.evidenceReference)))
    throw new Error("CREDIT_NOTE_REFUND_CONFIRMATION_REQUIRED");
}

/** Includes reserved batches: an ambiguous cash response must never release entitlement. */
export function creditNoteReservedRefundCents(operation: CreditNoteCommercialOperation): number {
  return operation.batches.reduce((total, batch) => total + (batch.request.refund?.amountCents ?? 0), 0);
}
export function creditNoteRefundDueCents(operation: CreditNoteCommercialOperation): number {
  return Math.max(0, operation.adjustmentCents - operation.debtReductionCents - operation.customerBalanceRestoreCents -
    operation.batches.filter(batch => batch.refund === "DONE")
      .reduce((total, batch) => total + (batch.request.refund?.amountCents ?? 0), 0));
}
export function creditNotePhysicalReturnPending(operation: CreditNoteCommercialOperation): boolean {
  return operation.returnLines.some(line => line.stockExpected &&
    operation.batches.filter(batch => batch.stock === "DONE").flatMap(batch => batch.request.receipts)
      .filter(receipt => receipt.originalLineId === line.originalLineId)
      .reduce((sum, receipt) => sum + returnQuantity(receipt.quantity), 0n) < returnQuantity(line.quantity));
}
export function assertCreditNoteCommercialOperation(raw: unknown): asserts raw is CreditNoteCommercialOperation {
  const value = raw as CreditNoteCommercialOperation;
  if (!value || value.type !== CREDIT_NOTE_COMMERCIAL_TYPE || value.schemaVersion !== 1 ||
      ![value.commercialOperationId, value.fiscalOperationId, value.tenantId, value.originalDocumentId,
        value.creditNoteDocumentId, value.saleId, value.saleSnapshotId, value.createdBy, value.debtIdempotencyKey].every(opaque) ||
      !["PEN", "USD"].includes(value.currency) || !cents(value.adjustmentCents) || !value.adjustmentCents ||
      !cents(value.debtReductionCents) || !cents(value.customerBalanceRestoreCents) ||
      value.debtReductionCents + value.customerBalanceRestoreCents > value.adjustmentCents ||
      !Array.isArray(value.returnLines) || !value.returnLines.length || value.returnLines.length > 256 ||
      !["PENDING", "DONE"].includes(value.debt) || !Array.isArray(value.batches) || value.batches.length > 1000 ||
      !["PENDING", "APPLYING", "COMPLETED", "ACTION_REQUIRED"].includes(value.status) ||
      !Number.isSafeInteger(value.createdAt) || !Number.isSafeInteger(value.updatedAt) || value.updatedAt < value.createdAt)
    throw new Error("CREDIT_NOTE_RETURN_OPERATION_INVALID");
  const facts = value.moneyFacts;
  if (!facts || ![facts.outstandingDebtCents, facts.refundablePaidCents,
      facts.appliedCustomerBalanceCents, facts.unverifiedCents].every(cents) ||
      value.debtReductionCents > facts.outstandingDebtCents || value.customerBalanceRestoreCents > facts.appliedCustomerBalanceCents ||
      (value.debtReductionCents + value.customerBalanceRestoreCents > 0 && ![facts.clientId, facts.accountId, facts.saleDebtMovementId].every(opaque)))
    throw new Error("CREDIT_NOTE_RETURN_MONEY_FACTS_INVALID");
  const lines = new Map<string, bigint>();
  const received = new Map<string, bigint>();
  for (const line of value.returnLines) {
    if (!opaque(line.originalLineId) || typeof line.stockExpected !== "boolean" || lines.has(line.originalLineId))
      throw new Error("CREDIT_NOTE_RETURN_LINES_INVALID");
    lines.set(line.originalLineId, returnQuantity(line.quantity));
  }
  const requests = new Set<string>(); const identities = new Set<string>();
  for (const batch of value.batches) {
    assertCreditNoteCommercialRequest(batch.request);
    if (requests.has(batch.request.requestId) || !opaque(batch.requestFingerprint) || !opaque(batch.actorId) ||
        !Number.isSafeInteger(batch.createdAt) || !["PENDING", "DONE"].includes(batch.stock) ||
        !["PENDING", "DONE"].includes(batch.refund) || !Array.isArray(batch.stockIdentities) ||
        batch.stockIdentities.length !== batch.request.receipts.length ||
        (batch.request.refund !== null && !opaque(batch.refundMovementId)))
      throw new Error("CREDIT_NOTE_RETURN_BATCH_INVALID");
    requests.add(batch.request.requestId);
    for (const receipt of batch.request.receipts) {
      if (!value.returnLines.some(line => line.originalLineId === receipt.originalLineId && line.stockExpected))
        throw new Error("CREDIT_NOTE_RETURN_LINE_NOT_STOCKED");
      const total = (received.get(receipt.originalLineId) ?? 0n) + returnQuantity(receipt.quantity);
      if (total > (lines.get(receipt.originalLineId) ?? 0n)) throw new Error("CREDIT_NOTE_RETURN_QUANTITY_EXCEEDED");
      received.set(receipt.originalLineId, total);
    }
    for (const identity of batch.stockIdentities) {
      for (const id of [identity.movementId, identity.movementLineId, identity.movementOperationId, identity.idempotencyKey]) {
        if (!opaque(id) || identities.has(id)) throw new Error("CREDIT_NOTE_RETURN_IDENTITY_INVALID");
        identities.add(id);
      }
    }
    if (batch.refundMovementId) {
      if (identities.has(batch.refundMovementId)) throw new Error("CREDIT_NOTE_RETURN_IDENTITY_INVALID");
      identities.add(batch.refundMovementId);
    }
  }
  if (creditNoteReservedRefundCents(value) + value.debtReductionCents + value.customerBalanceRestoreCents > value.adjustmentCents ||
      creditNoteReservedRefundCents(value) > facts.refundablePaidCents)
    throw new Error("CREDIT_NOTE_RETURN_REFUND_EXCEEDED");
  if (value.status === "COMPLETED" && (value.debt !== "DONE" || creditNoteRefundDueCents(value) > 0 || creditNotePhysicalReturnPending(value) ||
      value.batches.some(batch => batch.stock !== "DONE" || batch.refund !== "DONE")))
    throw new Error("CREDIT_NOTE_RETURN_COMPLETION_INVALID");
}
